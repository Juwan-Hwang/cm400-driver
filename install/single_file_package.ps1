<#
    single_file_package.ps1 - build the ONE distributable file for rc4 and prove the order of operations.

    The published package is a single `cm400-setup.exe` that carries its own driver package, daemon image,
    catalog, digest manifest and licence text. The sequence below is not stylistic:

      build -> sign the CATALOG over the payload -> append the payload -> verify the assembled bytes
      -> sign the HOST and timestamp it -> verify the SIGNED host -> publish that host's SHA-256

    Nothing modifies the host after step 5. Signing last is what makes the appended payload covered by the
    outer signature, and verifying the signed file - not just the pre-signature one - is what proves the
    reader can still find the bundle past the certificate table and its alignment padding.

    What the outer signature does NOT do is replace the inner chain: the catalog is still verified against
    the pinned publishing identity, the INF and the manifest are still proven to be catalog members, and
    every listed digest is still re-hashed from the bytes on disk, all before any machine state could be
    touched. `-NoSigning` builds the same shape without a catalog or a signature for CI checks; its output
    is not distributable.

    .\install\single_file_package.ps1 [-Out <dir>] [-SkipBuild] [-NoSigning]
#>
param(
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot),
    [string]$Out = '',
    [switch]$SkipBuild,
    [switch]$NoSigning
)
$ErrorActionPreference = 'Stop'
if (-not $Out) { $Out = Join-Path $RepoRoot 'dist\single-file' }
$payload = Join-Path $Out 'payload'
$report = Join-Path $Out 'single-file-report.txt'
$shipped = Join-Path $Out 'cm400-setup.exe'
New-Item -ItemType Directory -Force -Path $Out | Out-Null
function Say([string]$m) { Write-Host $m; Add-Content -Path $report -Value $m -Encoding utf8 }
function Hash([string]$p) { (Get-FileHash $p -Algorithm SHA256).Hash.ToUpperInvariant() }
Set-Content -Path $report -Value ("=== single-file package " + (Get-Date).ToUniversalTime().ToString('o') + " ===") -Encoding utf8

$env:CARGO_TARGET_DIR = if ($env:CARGO_TARGET_DIR) { $env:CARGO_TARGET_DIR } else { Join-Path $RepoRoot 'target' }
$target = (& cargo metadata --format-version 1 --no-deps --manifest-path (Join-Path $RepoRoot 'Cargo.toml') | ConvertFrom-Json).target_directory
$tool = Join-Path $target 'release\cm400-bundle.exe'
$catsig = Join-Path $target 'release\cm400-catsig.exe'

# --- [1] build everything that goes inside, before anything is packaged ------------------------
Say '== [1] release build =='
if ($SkipBuild) {
    Say '  -SkipBuild: relying on the tree that is already there'
} else {
    $b = & cargo build --release --workspace --manifest-path (Join-Path $RepoRoot 'Cargo.toml') 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) { throw "release build failed ($LASTEXITCODE):`n$($b -split "`r?`n" | Select-Object -Last 12)" }
    Say '  cargo build --release --workspace: ok'
}
foreach ($p in $tool, $catsig, (Join-Path $target 'release\cm400-setup.exe'), (Join-Path $target 'release\cm400d.exe')) {
    if (-not (Test-Path $p)) { throw "expected a release build of $(Split-Path $p -Leaf); it is not in $target\release" }
}
# freshness, proven by the build system rather than by mtimes: comparing every binary against the newest
# tracked source would refuse this run forever, because changing the installer's source cannot and should
# not relink the daemon. A second build that compiles nothing is the claim that matters.
. (Join-Path $PSScriptRoot 'build_inputs.ps1')
Say ('  ' + (Assert-NothingLeftToCompile -RepoRoot $RepoRoot))

# --- [2] the payload, and the catalog that attests it ------------------------------------------
Say '== [2] payload and its signed catalog =='
if (Test-Path $payload) { Remove-Item $payload -Recurse -Force }
New-Item -ItemType Directory -Force -Path $payload | Out-Null
if ($NoSigning) {
    # CI needs the same tree shape without an identity. The catalog and manifest are what the installer
    # judges, so an unsigned tree is assembled by hand and said out loud to be undistributable.
    Say '  -NoSigning: assembling without a catalog. This output cannot be installed or shipped.'
    Copy-Item (Join-Path $RepoRoot 'install\cm400.inf') $payload -Force
    Copy-Item (Join-Path $target 'release\cm400d.exe') $payload -Force
    Copy-Item (Join-Path $RepoRoot 'LICENSE') $payload -Force
    # the public half of the identity is public material and belongs in the bundle; the catalog's own
    # thumbprint file is generated by signing, so an unsigned shape has no such fact to record
    Copy-Item (Join-Path $RepoRoot 'install\cm400-release.cer') (Join-Path $payload 'cm400.cer') -Force
    $sums = @(Get-ChildItem $payload -File | Sort-Object Name | ForEach-Object { "{0}  {1}" -f (Hash $_.FullName), $_.Name })
    Set-Content -Path (Join-Path $payload 'SHA256SUMS.txt') -Value $sums -Encoding ascii
} else {
    & (Join-Path $PSScriptRoot 'sign_fixed_identity.ps1') -RepoRoot $RepoRoot -OutDir $payload -Timestamp -InnerPayload -AssumeCurrent
    if ($LASTEXITCODE -ne 0) { throw "payload signing failed ($LASTEXITCODE)" }
    foreach ($n in 'cm400.cat', 'SHA256SUMS.txt') {
        if (-not (Test-Path (Join-Path $payload $n))) { throw "sign_fixed_identity produced no $n" }
    }
}
$leftover = @(Get-ChildItem $payload -File | Where-Object { $_.Extension -in '.cdf', '.pdb' -or $_.Name -in 'cm400-setup.exe', 'cm400ctl.exe' })
if ($leftover.Count) { throw "non-payload files reached the bundle source: $($leftover.Name -join ', ')" }
Say ('  payload: ' + ((Get-ChildItem $payload -File | Sort-Object Name | ForEach-Object { $_.Name }) -join ', '))

# --- [3] append the payload to the host -------------------------------------------------------
Say '== [3] pack the bundle into the host =='
$files = @(Get-ChildItem $payload -File | Sort-Object Name | ForEach-Object { $_.FullName })
if (Test-Path $shipped) { Remove-Item $shipped -Force }
$pack = & $tool pack --host (Join-Path $target 'release\cm400-setup.exe') --out $shipped --files $files 2>&1 | Out-String
if ($LASTEXITCODE -ne 0) { throw "cm400-bundle pack failed:`n$pack" }
($pack -split "`r?`n" | Where-Object { $_.Trim() }) | ForEach-Object { Say ("  " + $_.Trim()) }
$hostSrc = (Get-Item (Join-Path $target 'release\cm400-setup.exe')).Length
Say ('  host ' + $hostSrc + 'B -> packed ' + (Get-Item $shipped).Length + 'B')

# --- [4] verify the assembled file BEFORE it is signed ----------------------------------------
Say '== [4] verify the packed host (pre-signature) =='
function Verify-At([string]$where, [string]$label) {
    $st = Join-Path $Out ("stage-" + $label)
    if (Test-Path $st) { Remove-Item $st -Recurse -Force }
    New-Item -ItemType Directory -Force -Path $st | Out-Null
    $ex = & $tool extract $where --to $st 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) { throw "[$label] extraction refused: $ex" }
    $bad = @()
    foreach ($f in (Get-ChildItem $st -File)) {
        $want = Hash (Join-Path $payload $f.Name)
        if ($want -ne (Hash $f.FullName)) { $bad += $f.Name }
    }
    $missing = @(Get-ChildItem $payload -File | Where-Object { -not (Test-Path (Join-Path $st $_.Name)) } | ForEach-Object { $_.Name })
    $extra = @(Get-ChildItem $st -File | Where-Object { -not (Test-Path (Join-Path $payload $_.Name)) } | ForEach-Object { $_.Name })
    if ($bad.Count -or $missing.Count -or $extra.Count) {
        throw "[$label] payload did not reproduce exactly: differs=$($bad -join ',') missing=$($missing -join ',') extra=$($extra -join ',')"
    }
    Say ("  [$label] every member re-extracted and re-hashed identical to the payload (" + (Get-ChildItem $st -File).Count + " files)")
    return $st
}
$pre = Verify-At $shipped 'pre-sign'
if (-not $NoSigning) {
    # both catalog members have to be bound: the design is that the manifest travels INSIDE the signed
    # catalog, so a checker that expects a single member is describing a different package than this one
    $cv = & $catsig verify --cat (Join-Path $payload 'cm400.cat') --cer (Join-Path $payload 'cm400.cer') --bind ("cm400.inf=" + (Join-Path $payload 'cm400.inf')) --bind ("SHA256SUMS.txt=" + (Join-Path $payload 'SHA256SUMS.txt')) 2>&1 | Out-String
    if ($cv -notmatch 'ACCEPTED') { throw "inner catalog verification did not accept the payload:`n$cv" }
    ($cv -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -Last 6) | ForEach-Object { Say ('    ' + $_.Trim()) }
    Say '  [pre-sign] cm400-catsig verdict: ACCEPTED (signature, embedded identity, content binding)'
}

# --- [5] sign the final host, then stop touching it -------------------------------------------
Say '== [5] sign the complete EXE and add an RFC 3161 timestamp =='
if ($NoSigning) {
    Say '  -NoSigning: the host is left unsigned'
} else {
    $fp = $null
    foreach ($line in Get-Content (Join-Path $RepoRoot 'install\cm400-release.thumbprint.txt')) {
        if ($line -match '^\s*thumbprint\s*=\s*([0-9A-Fa-f]{40})\s*$') { $fp = $Matches[1].ToUpper() }
    }
    if (-not $fp) { throw 'no 40-hex thumbprint in install\cm400-release.thumbprint.txt' }
    $kit = Get-ChildItem 'C:\Program Files (x86)\Windows Kits\10\bin' -Directory |
        Where-Object { Test-Path (Join-Path $_.FullName 'x64\signtool.exe') } |
        Sort-Object Name -Descending | Select-Object -First 1
    $signtool = Join-Path $kit.FullName 'x64\signtool.exe'
    $sizeBefore = (Get-Item $shipped).Length
    $s = & $signtool sign /fd SHA256 /sha1 $fp /tr http://timestamp.digicert.com /td SHA256 $shipped 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) { throw "signtool sign failed (exit $LASTEXITCODE):`n$s" }
    ($s -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 3) | ForEach-Object { Say ('  ' + $_.Trim()) }
    Say ('  signed: ' + $sizeBefore + 'B -> ' + (Get-Item $shipped).Length + 'B; identity ' + $fp)
    $v = & $signtool verify /v $shipped 2>&1 | Out-String
    Say ('  signtool verify exit=' + $LASTEXITCODE + '  (a non-zero here is the chain-trust verdict for a self-signed publisher, recorded and not conflated with signature validity)')
    ($v -split "`r?`n" | Where-Object { $_ -match 'Verify|timestamp|error' } | Select-Object -First 4) | ForEach-Object { Say ('    ' + $_.Trim()) }
}

# --- [6] verify the shipped artifact, past the signature --------------------------------------
Say '== [6] verify the SIGNED host =='
if (-not $NoSigning) {
    $list = & $tool list $shipped 2>&1 | Out-String
    if ($LASTEXITCODE -ne 0) { throw "the signed host cannot be read:`n$list" }
    ($list -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 2) | ForEach-Object { Say ('  ' + $_.Trim()) }
    if ($list -notmatch 'certificate table at') { throw 'the signed host does not report a certificate table; the signature is not where this script thinks it put it' }
    $post = Verify-At $shipped 'post-sign'
    Remove-Item $post -Recurse -Force -EA SilentlyContinue
    # the strongest check is the shipped file judging itself through the same code path an install takes.
    # It can only run elevated, because the staging directory it needs is closed to ordinary users by
    # design - so an unelevated packaging run records the omission instead of pretending it passed.
    $isAdm = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
        ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
    if ($isAdm) {
        $self = & $shipped verify-package 2>&1 | Out-String
        $code = $LASTEXITCODE
        ($self -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 14) | ForEach-Object { Say ('    ' + $_.Trim()) }
        Say ("  the shipped installer verified its own payload: exit $code")
        if ($code -ne 0 -and $code -ne 39) { throw "the shipped file does not verify itself (exit $code)" }
    } else {
        Say '  self-verify by the shipped EXE: SKIPPED here because this shell is not elevated - it is part of the elevated release gate, not something to wave through'
    }
}
Remove-Item $pre -Recurse -Force -EA SilentlyContinue
$extra = @(Get-ChildItem $Out -Recurse -File | Where-Object { $_.FullName -notlike ($payload + '*') -and $_.Name -notin 'cm400-setup.exe', 'single-file-report.txt' })
Say ('  leftovers in the output tree outside payload/: ' + $extra.Count + ' (expected 0)')

# --- [7] the one hash the release will publish ------------------------------------------------
Say '== [7] final artifact =='
$sha = Hash $shipped
Say ('  file    : ' + $shipped)
Say ('  size    : ' + (Get-Item $shipped).Length + 'B')
Say ('  sha256  : ' + $sha + '   <- the single value to publish; one download, one hash to check')
Say ('  report  : ' + $report)
if ($NoSigning) { Say '  NOTE: -NoSigning output is a CI shape only. It has no catalog and no signature and must never be uploaded.' }
# the packing chain deliberately ends by asking tools that report nonzero for reasons this script has
# already judged (an untrusted self-signed chain, for instance); state the script's own verdict explicitly
# so `pwsh -File` never reports somebody else's status code as this run's outcome
exit 0
